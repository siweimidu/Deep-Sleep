// Generates src/data.rs from the app's own dictionaries, so the 269 messages are transcribed by a
// program instead of by hand (and any key drift fails loudly here).
//
// usage: node rust/index-rs/gen-data.mjs
import { writeFileSync } from 'node:fs'

const repo = new URL('../../', import.meta.url)
const { zh } = await import(new URL('src/i18n/zh.ts', repo).href)
const { en } = await import(new URL('src/i18n/en.ts', repo).href)

const keys = Object.keys(zh)
const missingInEnglish = keys.filter((key) => !(key in en))
const extraInEnglish = Object.keys(en).filter((key) => !(key in zh))
if (missingInEnglish.length || extraInEnglish.length) {
  throw new Error(`key drift: en missing [${missingInEnglish}] / en extra [${extraInEnglish}]`)
}

const escape = (text) =>
  text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')

const rows = keys
  .map((key) => `    ("${escape(key)}", "${escape(zh[key])}", "${escape(en[key])}"),`)
  .join('\n')

// `mod data;` is declared inside port.rs, so the file must be port/data.rs.
writeFileSync(
  new URL('src/port/data.rs', import.meta.url),
  `// generated by gen-data.mjs from src/i18n/{zh,en}.ts — do not edit by hand
pub static MESSAGES: &[(&str, &str, &str)] = &[
${rows}
];
`,
)
console.log(`wrote src/port/data.rs: ${keys.length} keys, zh + en`)
