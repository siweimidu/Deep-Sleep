/// Port of `getFileExt` (`src/services/attachments.ts:21`).
///
/// `name.lastIndexOf('.') > 0`, so a leading dot is not an extension and a trailing dot yields "".
pub fn get_file_ext(name: String) -> Result<Value, String> {
    Ok(Value::String(file_ext(&name)))
}

/// Port of `isAcceptedExt` (`src/services/attachments.ts:26`).
pub fn is_accepted_ext(name: String) -> Result<Value, String> {
    Ok(Value::Bool(is_accepted(&file_ext(&name))))
}

/// Port of `getUploadPurpose` (`src/services/attachments.ts:32`).
///
/// The source returns `FilePurpose | null`; `null` crosses as `Value::Null`, not `None`.
pub fn get_upload_purpose(name: String, is_image: bool) -> Result<Value, String> {
    Ok(if is_image {
        Value::Null
    } else if is_layout_recognition(&file_ext(&name)) {
        Value::String("rich_layout_recognition".into())
    } else {
        Value::String("user_data".into())
    })
}

/// Port of `validateFiles` (`src/services/attachments.ts:46`).
///
/// `files` is typed `File[]`, so it arrives as a structured value: a non-array must fail the way
/// `files.some` fails in JS, and reading `.name` off a null element is a V8 TypeError.
pub fn validate_files(files: Value, current_count: f64) -> Result<Value, String> {
    let items = match &files {
        Value::Array(items) => items,
        Value::Null => return Err(reading_error("null", "some")),
        value if js::is_undefined(value) => return Err(reading_error("undefined", "some")),
        _ => return Err("files.some is not a function".into()),
    };
    for file in items {
        let name = js_name(prop(file, "name")?)?;
        if !is_accepted(&file_ext(&name)) {
            return Ok(json!({ "key": "uploadUnsupportedFormat" }));
        }
    }
    let mut oversized: Option<&Value> = None;
    for file in items {
        let size = js_number(prop(file, "size")?);
        if size > max_size_mb(file)? * 1024.0 * 1024.0 {
            oversized = Some(file);
            break;
        }
    }
    if let Some(file) = oversized {
        let size = max_size_mb(file)?;
        return Ok(json!({ "key": "uploadMaxMBSize", "params": { "size": js::number(size) } }));
    }
    if current_count + items.len() as f64 > 50.0 {
        return Ok(json!({ "key": "uploadMaxFiles", "params": { "count": 50 } }));
    }
    Ok(Value::Null)
}

/// Port of `resolveMimeType` (`src/services/attachments.ts:223`).
pub fn resolve_mime_type(file: Value) -> Result<Value, String> {
    mime_type(&file)
}

/// Port of `isImage` (`src/services/attachments.ts:225`).
pub fn is_image(mime_type: String) -> Result<Value, String> {
    Ok(Value::Bool(mime_type.starts_with("image/")))
}

/// Port of `getExtension` (`src/services/attachments.ts:228`).
pub fn get_extension(name: String) -> Result<Value, String> {
    Ok(Value::String(match name.rfind('.') {
        Some(dot) if dot > 0 => name[dot + 1..].to_uppercase(),
        _ => String::new(),
    }))
}

/// Port of `formatSize` (`src/services/attachments.ts:233`).
pub fn format_size(bytes: f64) -> Result<Value, String> {
    if bytes < 1024.0 {
        return Ok(Value::String(format!("{} B", js::number_to_string(bytes))));
    }
    let units = ["KB", "MB", "GB"];
    let mut value = bytes / 1024.0;
    let mut unit = 0;
    while value >= 1024.0 && unit < units.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    let printed = if value < 10.0 {
        to_fixed_1(value)
    } else {
        js::number_to_string(js::math_round(value))
    };
    Ok(Value::String(format!("{} {}", printed, units[unit])))
}

// ---- helpers --------------------------------------------------------------------------------

/// `name.lastIndexOf('.')`, then the slice after it, lowercased. `.` is ASCII, so byte indices and
/// UTF-16 indices agree on where the extension starts.
fn file_ext(name: &str) -> String {
    match name.rfind('.') {
        Some(dot) if dot > 0 => name[dot + 1..].to_lowercase(),
        _ => String::new(),
    }
}

fn is_accepted(ext: &str) -> bool {
    ACCEPT_FILE_EXTS.contains(&ext)
}

fn is_layout_recognition(ext: &str) -> bool {
    LAYOUT_RECOGNITION_EXTS.contains(&ext)
}

fn mime_by_ext(ext: &str) -> Option<&'static str> {
    match ext {
        "png" => Some("image/png"),
        "jpg" | "jpeg" => Some("image/jpeg"),
        "gif" => Some("image/gif"),
        "webp" => Some("image/webp"),
        _ => None,
    }
}

/// V8's message for reading a property of `null` / `undefined`.
fn reading_error(base: &str, prop: &str) -> String {
    format!("Cannot read properties of {base} (reading '{prop}')")
}

/// `value[prop]` with JS semantics: objects answer, everything else is `undefined`.
fn prop<'a>(value: &'a Value, name: &str) -> Result<Option<&'a Value>, String> {
    if value.is_null() {
        return Err(reading_error("null", name));
    }
    if js::is_undefined(value) {
        return Err(reading_error("undefined", name));
    }
    Ok(match value {
        Value::Object(map) => map.get(name),
        _ => None,
    })
}

/// A string read off a JS value, or the TypeError `getFileExt` raises on it.
fn js_name(value: Option<&Value>) -> Result<String, String> {
    let value = match value {
        None => return Err(reading_error("undefined", "lastIndexOf")),
        Some(value) => value,
    };
    if value.is_null() {
        return Err(reading_error("null", "lastIndexOf"));
    }
    if js::is_undefined(value) {
        return Err(reading_error("undefined", "lastIndexOf"));
    }
    match value {
        Value::String(text) => Ok(text.clone()),
        value => match js::string_units(value) {
            Some(units) => Ok(String::from_utf16_lossy(&units)),
            None => Err("name.lastIndexOf is not a function".into()),
        },
    }
}

fn mime_type(file: &Value) -> Result<Value, String> {
    if let Some(given) = prop(file, "type")?
        && truthy(given)
    {
        return Ok(given.clone());
    }
    let ext = file_ext(&js_name(prop(file, "name")?)?);
    Ok(Value::String(mime_by_ext(&ext).unwrap_or_default().into()))
}

fn max_size_mb(file: &Value) -> Result<f64, String> {
    let mime = mime_type(file)?;
    let image = match &mime {
        Value::String(text) => text.starts_with("image/"),
        Value::Object(map) if map.len() == 1 && map.get("$utf16").is_some() => {
            crate::js::string_units(&mime)
                .map(|units| String::from_utf16_lossy(&units).starts_with("image/"))
                .unwrap_or(false)
        }
        _ => return Err("mimeType.startsWith is not a function".into()),
    };
    let purpose = get_upload_purpose(js_name(prop(file, "name")?)?, image)?;
    Ok(if purpose == Value::String("user_data".into()) {
        32.0
    } else {
        64.0
    })
}

/// JS truthiness, including the wire markers for `undefined` and `NaN`.
fn truthy(value: &Value) -> bool {
    match value {
        Value::Null => false,
        Value::Bool(flag) => *flag,
        Value::Number(number) => number.as_f64().is_some_and(|x| x != 0.0 && !x.is_nan()),
        Value::String(text) => !text.is_empty(),
        Value::Array(_) => true,
        value => match js::as_number(value) {
            Some(number) => number != 0.0 && !number.is_nan(),
            None => !js::is_undefined(value),
        },
    }
}

/// JS `Number(value)` for the relational comparison `file.size > limit`.
fn js_number(value: Option<&Value>) -> f64 {
    match value {
        None => f64::NAN,
        Some(Value::Null) => 0.0,
        Some(Value::Bool(flag)) => f64::from(u8::from(*flag)),
        Some(Value::String(text)) => {
            let trimmed = text.trim();
            if trimmed.is_empty() {
                0.0
            } else {
                trimmed.parse().unwrap_or(f64::NAN)
            }
        }
        Some(value) => js::as_number(value).unwrap_or(f64::NAN),
    }
}

/// JS `Number.prototype.toFixed(1)`: the nearest tenth, ties away from zero, on the exact value.
fn to_fixed_1(x: f64) -> String {
    if x.is_nan() {
        return "NaN".into();
    }
    if !x.is_finite() || x.abs() >= 1e21 {
        return js::number_to_string(x);
    }
    let negative = x < 0.0;
    let magnitude = x.abs();
    // 20 decimals is past the last digit of any double below 1e21, so this is the exact value.
    let exact = format!("{magnitude:.20}");
    let (whole, fraction) = exact.split_once('.').unwrap_or((exact.as_str(), "0"));
    let tenths = whole.parse::<u128>().unwrap_or(0) * 10
        + u128::from(fraction.as_bytes().first().copied().unwrap_or(b'0') - b'0')
        + u128::from(
            fraction
                .as_bytes()
                .get(1)
                .is_some_and(|digit| *digit >= b'5'),
        );
    format!(
        "{}{}.{}",
        if negative { "-" } else { "" },
        tenths / 10,
        tenths % 10
    )
}

