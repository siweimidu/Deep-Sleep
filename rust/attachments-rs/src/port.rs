//! The Rust port of `src/services/attachments.ts`.
//!
//! Only the pure classification helpers are ported: extension tables, MIME resolution, the
//! add-time validation and the size formatter. The upload orchestration in the same file
//! (`onUploadNotice`, `uploadAttachment`, `cancelUpload`, `describeUploadError`,
//! `describeUploadQuota`) stays in TypeScript — see `rust-anything.json` → `js_only`.

#![forbid(unsafe_code)]

