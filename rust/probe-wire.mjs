// Feasibility probe: can the generated Node glue be reused as the browser binary-wire codec?
//
// `index.cjs` hard-codes `const native = require('./pkg/x.js')` on line 1 and everything else is
// pure logic plus `module.exports.x = ...`. If the only Node dependency is that line, wrapping the
// rest in a factory that takes `native` gives the browser the same binary codec (generic `wDyn`
// encode + schema-specific generated decode) that `rust-anything diff` already validated.
//
// usage: node rust/probe-wire.mjs <crate>        e.g. node rust/probe-wire.mjs branches-rs
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const repo = new URL('../', import.meta.url)
const crate = process.argv[2] ?? 'branches-rs'
const crateDir = new URL(`rust/${crate}/`, repo)

const source = readFileSync(new URL('index.cjs', crateDir), 'utf8')
const loader = /^const native = require\([^)]*\)\s*$/m
if (!loader.test(source)) throw new Error('unexpected index.cjs: the native require line was not found')
if (/^\s*exports\./m.test(source)) throw new Error('unexpected index.cjs: bare `exports.` assignments')
if ((source.match(/require\(/g) ?? []).length !== 1) throw new Error('index.cjs requires more than the wasm glue')

const name = ([...source.matchAll(/name = "([^"]+)"/g)][0] ?? [])[1]
const factory = `// generated by rust/probe-wire.mjs — do not edit
export const createCodec = (native) => {
  const module = { exports: {} }
${source.replace(loader, '')}
  return module.exports
}
`
const outPath = join(process.env.TEMP, `wire-${crate}.mjs`)
writeFileSync(outPath, factory)

const realFetch = globalThis.fetch
globalThis.fetch = async (input, init) => {
  const url = input instanceof URL ? input : new URL(String(input))
  if (url.protocol !== 'file:') return realFetch(input, init)
  return new Response(readFileSync(url), { headers: { 'content-type': 'application/wasm' } })
}

const snake = crate.replace('-', '_')
const glue = await import(new URL(`src/rust-core/pkg/${snake}.js`, repo).href)
await glue.default({ module_or_path: new URL(`src/rust-core/pkg/${snake}_bg.wasm`, repo) })

const codec = (await import(`file:///${outPath.replace(/\\/g, '/')}`)).createCodec(glue)
console.log('codec exports:', Object.keys(codec).join(', '))

// Correctness first: same session through the original TS and through the binary wire.
const { getVisibleMessages } = await import(new URL('src/services/chat/branches.ts', repo).href)
const session = {
  id: 's1',
  title: 'probe',
  createdAt: 0,
  updatedAt: 0,
  rootMessageId: 'm0',
  messages: [
    { id: 'm0', role: 'user', content: 'hi', createdAt: 0, parentId: null, selectedChildId: 'm1' },
    { id: 'm1', role: 'assistant', content: 'yo', createdAt: 1, parentId: 'm0', selectedChildId: 'm2' },
    { id: 'm2', role: 'user', content: 'more', createdAt: 2, parentId: 'm1' },
  ],
}
const expected = JSON.stringify(getVisibleMessages(session))
const got = JSON.stringify(codec.getVisibleMessages(session))
console.log('TS  :', expected)
console.log('wire:', got)
console.log(got === expected ? 'MATCH' : 'MISMATCH')
process.exit(got === expected ? 0 : 1)
